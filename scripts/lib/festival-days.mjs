/** 回傳 today（YYYY-MM-DD）起 lead 天內、尚未過期的節點。純函式，供測試。 */
export function upcomingFestivals(todayYmd, list = FESTIVAL_DAYS, lead = LEAD_DAYS) {
  const t = Date.parse(`${todayYmd}T00:00:00Z`);
  return list.filter((f) => {
    const d = Date.parse(`${f.date}T00:00:00Z`);
    const diff = (d - t) / 86400000;
    return diff >= 0 && diff <= lead;
  });
}
