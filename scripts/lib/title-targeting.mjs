/**
 * 產生要注入產線 prompt 的標題瞄準規則區塊。
 * @param {'civic'|'police'|'video'|'international'|'health-days'} kind
 * @returns {string[]} prompt 行陣列（直接展開進既有的 prompt 陣列）
 */
export function renderTitleTargeting(kind) {
  const f = FLAVORS[kind];
  if (!f) throw new Error(`renderTitleTargeting：未知的 kind「${kind}」`);
  return [
    '【標題瞄準（一票否決，寫完回頭自己檢查一次）】',
    f.nature,
    '',
    '先想清楚這篇要吃哪個查詢字，再下標。三個檢查：',
    '1. 那個字**不能只由專有名詞組成**（人名／機構名／產品型號／頻道名／活動全名）。要是概念詞或問題。',
    '2. **三個月後還有人搜這個字嗎？** 答不出「會」就重擬。',
    '3. **主標必須含那個字的核心詞**；事件、個案、影片可以寫進副標或第一段當引子，主標不行。',
    '',
    `本線的重點：${f.rule}`,
    '',
    '改寫示範（同一則素材，只換瞄準點）：',
    ...f.examples.flatMap(([bad, good]) => [`  ${bad}`, `  ${good}`, '']),
    '實測依據：本站已排到 Google 第一頁的 190 個字，平均每個字只有 6.9 次曝光；瞄準事件型專有名詞的',
    '文章排到第 5 名、90 天卻只有 11 次曝光，而唯一一篇「是什麼＋運作原理」的概念文拿到 177 次。',
    '排名不是問題，瞄準錯字才是。',
  ];
}
