const norm = (s) => s.toLowerCase().replace(/臺/g, '台').replace(/\s+/g, ' ').trim();

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * 片語比對。純 ASCII 片語（ai / got / ldl / esg…）必須落在單字邊界上，
 * 否則 'ai' 會命中 TAIPEI、'got' 會命中 forgot，把不相干的文章掃進來。
 * 含中日文的片語維持子字串比對（中文沒有空白分詞）。
 */
const matchCache = new Map();
function phraseHit(haystack, phrase) {
  const p = norm(phrase);
  if (!/^[\x00-\x7f]+$/.test(p)) return haystack.includes(p);
  let re = matchCache.get(p);
  if (!re) {
    re = new RegExp(`(?<![a-z0-9])${escapeRe(p)}(?![a-z0-9])`);
    matchCache.set(p, re);
  }
  return re.test(haystack);
}

/** 把一個原始標籤映射成 0..n 個受控標籤（受控標籤名本身也算一條命中片語） */
export function mapTag(raw) {
  const n = norm(raw);
  const hits = new Set();
  for (const [canonical, phrases] of Object.entries(RULES)) {
    for (const p of [canonical, ...phrases]) {
      if (phraseHit(n, p)) {
        hits.add(canonical);
        break;
      }
    }
  }
  return [...hits];
}

/** 把一篇文章的原始標籤陣列，映射成受控標籤陣列（含逐檔指定、兜底與上限） */
export function mapTags(rawTags, filename) {
  if (filename && OVERRIDES[filename]) return [...OVERRIDES[filename]];
  const out = new Set();
  for (const raw of rawTags) for (const t of mapTag(raw)) out.add(t);
  for (const [canonical, { match, exclude }] of Object.entries(BROAD)) {
    if (out.has(canonical)) continue;
    if (exclude.some((e) => out.has(e))) continue;
    const hit = rawTags.some((raw) => {
      const n = norm(raw);
      return match.some((p) => phraseHit(n, p));
    });
    if (hit) out.add(canonical);
  }
  return [...out].slice(0, MAX_TAGS);
}

// ── CLI ────────────────────────────────────────────────────────
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const write = process.argv.includes('--write');
  const unmappedOnly = process.argv.includes('--unmapped');

  const files = readdirSync(ARTICLE_DIR).filter((f) => /\.mdx?$/.test(f));
  const unmapped = new Map();
  const stats = { files: 0, changed: 0, emptied: 0, rawTotal: 0, newTotal: 0 };
  const canonCount = new Map();

  for (const f of files) {
    const full = path.join(ARTICLE_DIR, f);
    const raw = readFileSync(full, 'utf8');
    const m = raw.match(/^(---\r?\n)([\s\S]*?)(\r?\n---)/);
    if (!m) continue;
    const fm = yaml.load(m[2]);
    const rawTags = Array.isArray(fm?.tags) ? fm.tags : [];
    stats.files++;
    stats.rawTotal += rawTags.length;

    for (const t of rawTags) if (mapTag(t).length === 0) unmapped.set(t, (unmapped.get(t) || 0) + 1);

    const next = mapTags(rawTags, f);
    stats.newTotal += next.length;
    if (next.length === 0 && rawTags.length > 0) stats.emptied++;
    for (const t of next) canonCount.set(t, (canonCount.get(t) || 0) + 1);

    const same =
      next.length === rawTags.length && next.every((t, i) => t === rawTags[i]);
    if (!same) stats.changed++;

    if (write && !same) {
      // 逐行重建 frontmatter：只換掉 tags 區塊，其餘欄位、順序、行尾原樣保留。
      // （早期用單一 regex 取代，會連最後一個 list item 的換行一起吃掉，
      //   把下一個欄位黏成 `- "健保"author: luo-yang`。逐行處理沒有這個風險。）
      const lines = m[2].split('\n');
      const start = lines.findIndex((l) => /^tags:/.test(l));
      if (start === -1) {
        console.error(`  !! ${f}: 找不到 tags 區塊，跳過`);
        continue;
      }
      let end = start + 1; // 區塊式：往下吃連續的 `- ` 項目；流式（tags: [...]）則只有一行
      if (!/^tags:[ \t]*\S/.test(lines[start])) {
        while (end < lines.length && /^[ \t]*-[ \t]/.test(lines[end])) end++;
      }
      const yamlTags =
        next.length === 0
          ? ['tags: []']
          : ['tags:', ...next.map((t) => `  - ${JSON.stringify(t)}`)];
      lines.splice(start, end - start, ...yamlTags);
      writeFileSync(full, m[1] + lines.join('\n') + m[3] + raw.slice(m[0].length), 'utf8');
    }
  }

  if (unmappedOnly) {
    console.log(`沒被任何規則接住的原始標籤：${unmapped.size} 個`);
    for (const [t, c] of [...unmapped.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
      console.log(`  ${String(c).padStart(3)}  ${t}`);
    }
    process.exit(0);
  }

  console.log(`模式：${write ? '寫入' : 'dry-run'}`);
  console.log(`檔案 ${stats.files}，會變動 ${stats.changed} 篇`);
  console.log(`標籤總數 ${stats.rawTotal} → ${stats.newTotal}（每篇平均 ${(stats.newTotal / stats.files).toFixed(2)}）`);
  console.log(`受控標籤用到 ${canonCount.size} 個；映射後變空的文章 ${stats.emptied} 篇`);
  console.log(`未被規則接住的原始標籤 ${unmapped.size} 個（--unmapped 看清單）`);

  const zero = [];
  for (const t of Object.keys(RULES)) if (!canonCount.has(t)) zero.push(t);
  console.log(`\n沒有任何文章掛到的受控標籤：${zero.length} 個` + (zero.length ? `\n  ${zero.join('、')}` : ''));

  const thin = [...canonCount.entries()].filter(([, c]) => c < 3).sort((a, b) => a[1] - b[1]);
  console.log(`\n少於 3 篇的受控標籤：${thin.length} 個`);
  for (const [t, c] of thin) console.log(`  ${c}  ${t}`);

  console.log('\n=== 受控標籤文章數 top 30 ===');
  for (const [t, c] of [...canonCount.entries()].sort((a, b) => b[1] - a[1]).slice(0, 30)) {
    console.log(`  ${String(c).padStart(3)}  ${t}`);
  }
}
